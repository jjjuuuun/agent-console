/** 현재 언어의 문구(렌더 때 만든다). 목록 보기(`arrange`)는 공용 묶음에 이 화면 몫을 덧붙인 것이다. */
export function useResourceMessages() {
  const own = useMessageTable("resources", createResourceMessages);
  const arrange = useArrangeMessages();
  return useMemo(() => ({ ...own, arrange: mergeArrange(arrange, undefined) }), [own, arrange]);
}
export type ResourceMessages = ReturnType<typeof useResourceMessages>;
/** 목록 보기(`arrange`)를 합치기 전의 이 화면 문구. 화면 밖 순수 함수가 받는다. */
export type ResourceTexts = ReturnType<typeof createResourceMessages>;
