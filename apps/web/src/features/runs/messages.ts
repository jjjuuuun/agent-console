/** 상호작용 상태 → 칩 키(끊김 구분). */
export function interactionStateKey(i: Pick<Interaction, "status" | "close_reason">): string {
  return i.status === "expired" && i.close_reason === "interrupted" ? "interrupted" : i.status;
}

